            [0, 1,-1,-1, 1, 0,-1, 1, 1,-1, 0, 1,-1,-1, 1, 0,-1, 1, 1,-1, 0, 1,-1,-1, 1, 0,-1, 1, 1,-1], # A2g
            [0, 2,-2,-2, 2, 0, 1,-1,-1, 1, 0,-1, 1, 1,-1, 0,-2, 2, 2,-2, 0,-1, 1, 1,-1, 0, 1,-1,-1, 1], # Eg
